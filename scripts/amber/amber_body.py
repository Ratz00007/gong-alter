# ---------------------------------------------------------------- doc template
class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, 'bookmark_name'):
            level = getattr(flowable, 'bookmark_level', 0)
            text = getattr(flowable, 'bookmark_text', '')
            key = getattr(flowable, 'bookmark_key', '')
            # TOC must display the same number the footer prints on that page:
            # arabic, reset to 1 at the body start (front matter is roman).
            body_start = getattr(self, '_body_start_page', None)
            page = self.page
            if body_start is not None and page >= body_start:
                page = page - body_start + 1
            self.notify('TOCEntry', (level, text, page, key))

class BodyStartMarker(Spacer):
    """Zero-height marker: records the first body page so footers can switch
    from roman (front matter) to arabic (body, reset to 1).
    Sets unconditionally on every multiBuild pass - the final pass wins, so a
    TOC that grows between passes cannot leave a stale body-start page."""
    def __init__(self):
        Spacer.__init__(self, 0, 0)
    def draw(self):
        doc = getattr(self.canv, '_doctemplate', None)
        page = getattr(self.canv, 'getPageNumber', lambda: 0)()
        if doc is not None and not getattr(doc, '_body_start_fixed', False):
            doc._body_start_page = page

ROMAN = {1: 'i', 2: 'ii', 3: 'iii', 4: 'iv', 5: 'v', 6: 'vi', 7: 'vii', 8: 'viii', 9: 'ix', 10: 'x'}

def page_deco(canvas, doc):
    canvas.saveState()
    # header: muted title + accent rule
    canvas.setFont('FreeSerif', 7.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(MARGIN, PAGE_H - 50, DOC_TITLE.upper())
    canvas.setStrokeColor(ACCENT); canvas.setLineWidth(1.2)
    canvas.line(MARGIN, PAGE_H - 56, PAGE_W - MARGIN, PAGE_H - 56)
    # footer: light rule + author left + page number right
    canvas.setStrokeColor(BORDER); canvas.setLineWidth(0.5)
    canvas.line(MARGIN, 48, PAGE_W - MARGIN, 48)
    canvas.setFont('FreeSerif', 7.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(MARGIN, 37, DOC_AUTHOR)
    body_start = getattr(doc, '_body_start_page', None)
    if body_start is None or doc.page < body_start:
        label = ROMAN.get(doc.page, str(doc.page))
    else:
        label = str(doc.page - body_start + 1)
    canvas.drawRightString(PAGE_W - MARGIN, 37, label)
    canvas.restoreState()

# ---------------------------------------------------------------- helpers
def measure(el):
    w, h = el.wrap(AVAIL_W, AVAIL_H)
    return h

def safe_keep_together(elements):
    total = sum(measure(e) for e in elements if not isinstance(e, Spacer))
    if total <= MAX_KEEP:
        return [KeepTogether(elements)]
    if len(elements) >= 2:
        return [KeepTogether(elements[:2])] + list(elements[2:])
    return list(elements)

def add_heading(text, style, level=0):
    key = 'h_' + hashlib.md5((str(level) + text).encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p

def embed_image(path, max_width=None, max_height=None):
    if max_width is None: max_width = AVAIL_W
    if max_height is None: max_height = A4[1] * 0.35
    im = PILImage.open(path)
    ow, oh = im.size
    ratio = min(max_width / ow if ow > max_width else 1.0,
                max_height / oh if oh > max_height else 1.0,
                max_width / ow, max_height / oh)
    return Image(path, width=ow * ratio, height=oh * ratio)

def stat_row(items):
    cells, widths = [], []
    gap = 10
    n = len(items)
    w_each = (AVAIL_W - gap * (n - 1)) / n
    for value, label in items:
        inner = Table([[Paragraph('<b>%s</b>' % value, S['stat_big'])],
                       [Paragraph(label, S['stat_lab'])]], colWidths=[w_each - 2])
        inner.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), CARD_BG),
            ('BOX', (0, 0), (-1, -1), 1, ACCENT),
            ('TOPPADDING', (0, 0), (-1, 0), 9), ('BOTTOMPADDING', (0, 0), (-1, 0), 2),
            ('TOPPADDING', (0, 1), (-1, 1), 2), ('BOTTOMPADDING', (0, 1), (-1, 1), 9),
        ]))
        cells.append(inner); widths.append(w_each)
        if len(cells) < n:
            cells.append(''); widths.append(gap)
    t = Table([cells], colWidths=widths, hAlign='CENTER')
    t.setStyle(TableStyle([('VALIGN', (0, 0), (-1, -1), 'TOP'),
                           ('LEFTPADDING', (0, 0), (-1, -1), 0),
                           ('RIGHTPADDING', (0, 0), (-1, -1), 0)]))
    return t

def data_table(spec):
    headers, rows, ratios = spec['headers'], spec['rows'], spec['ratios']
    col_widths = [r * AVAIL_W for r in ratios]
    scale = (AVAIL_W * 0.995) / sum(col_widths)
    col_widths = [w * scale for w in col_widths]
    data = [[Paragraph('<b>%s</b>' % h, S['th']) for h in headers]]
    for row in rows:
        data.append([Paragraph(c, S['td']) for c in row])
    t = Table(data, colWidths=col_widths, hAlign='CENTER', repeatRows=1)
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, TABLE_ROW_ODD]),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('LEFTPADDING', (0, 0), (-1, -1), 7),
        ('RIGHTPADDING', (0, 0), (-1, -1), 7),
        ('TOPPADDING', (0, 0), (-1, -1), 5.5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5.5),
    ]))
    return t

def code_block(spec):
    return Preformatted(spec['text'], S['code'])

# ---------------------------------------------------------------- block engine
def render_blocks(blocks, story):
    chapter_no = 0
    i = 0
    while i < len(blocks):
        kind = blocks[i][0]
        spec = blocks[i][1] if len(blocks[i]) > 1 else None
        nxt = blocks[i + 1] if i + 1 < len(blocks) else None

        if kind == 'h1':
            chapter_no += 1
            title = '%d · %s' % (chapter_no, spec)
            head = add_heading(title, S['h1'], level=0)
            rule = HRFlowable(width='100%', thickness=1.1, color=ACCENT,
                              spaceBefore=2, spaceAfter=12)
            group = [head, rule]
            if nxt and nxt[0] == 'p':
                group.append(Paragraph(nxt[1], S['body']))
                i += 1
            story.append(CondPageBreak(H1_THRESHOLD))
            story.extend(safe_keep_together(group))
        elif kind == 'h2':
            head = add_heading(spec, S['h2'], level=1)
            group = [head]
            if nxt and nxt[0] == 'p':
                group.append(Paragraph(nxt[1], S['body']))
                i += 1
            story.extend(safe_keep_together(group))
        elif kind == 'h3':
            story.append(CondPageBreak(70))
            story.append(Paragraph('<b>%s</b>' % spec, S['h3']))
        elif kind == 'p':
            story.append(Paragraph(spec, S['body']))
        elif kind == 'bullets':
            for item in spec:
                story.append(Paragraph('•  %s' % item, S['bullet']))
            story.append(Spacer(1, 4))
        elif kind == 'stats':
            story.append(Spacer(1, 8))
            story.append(stat_row(spec))
            story.append(Spacer(1, 14))
        elif kind == 'table':
            cap = Paragraph(spec['caption'], S['caption'])
            t = data_table(spec)
            story.append(Spacer(1, 10))
            story.extend(safe_keep_together([t, Spacer(1, 6), cap]))
            story.append(Spacer(1, 14))
        elif kind == 'figure':
            img = embed_image(os.path.join(BUILD_DIR, spec['path']),
                              max_width=AVAIL_W, max_height=spec.get('max_h', 300))
            cap = Paragraph(spec['caption'], S['caption'])
            story.append(Spacer(1, 14))
            story.extend(safe_keep_together([img, Spacer(1, 7), cap]))
            story.append(Spacer(1, 16))
        elif kind == 'code':
            story.append(Spacer(1, 8))
            story.append(code_block(spec))
            if spec.get('caption'):
                story.append(Spacer(1, 5))
                story.append(Paragraph(spec['caption'], S['caption']))
            story.append(Spacer(1, 12))
        i += 1

# ---------------------------------------------------------------- build
def make_doc():
    doc = TocDocTemplate(
        OUT_BODY, pagesize=A4,
        leftMargin=MARGIN, rightMargin=MARGIN,
        topMargin=TOP_MARGIN, bottomMargin=BOTTOM_MARGIN,
        title='AMBER - Personal Revenue Intelligence Platform: Architecture and Product Blueprint v1.0',
        author='Z.ai', creator='Z.ai',
        subject='Blueprint for a personal, hybrid (local + cloud) revenue intelligence platform: architecture, AI routing, data model, features, design system, roadmap.')
    doc._body_start_page = None
    return doc

def build_story():
    from content_1 import C1
    from content_2 import C4, C5, C6
    from content_3 import C7, C8, C9, C10
    story = []
    story.append(Paragraph('<b>Table of Contents</b>', S['toc_title']))
    toc = TableOfContents()
    toc.levelStyles = [TOC_L0, TOC_L1]
    story.append(toc)
    story.append(PageBreak())          # structural: TOC -> body (allowed)
    story.append(BodyStartMarker())
    # single pass over ALL chapters so the chapter counter stays continuous
    render_blocks(C1 + C4 + C5 + C6 + C7 + C8 + C9 + C10, story)
    return story

def main():
    # Phase A: discover the true body-start page (TOC may grow across passes).
    doc = make_doc()
    doc.multiBuild(build_story(), onFirstPage=page_deco, onLaterPages=page_deco)
    body_start = getattr(doc, '_body_start_page', None) or 2
    # Phase B: rebuild with the boundary fixed from page 1 so footers and TOC agree.
    doc2 = make_doc()
    doc2._body_start_page = body_start
    doc2._body_start_fixed = True
    doc2.multiBuild(build_story(), onFirstPage=page_deco, onLaterPages=page_deco)
    print('built', OUT_BODY, '| body starts at pdf page', body_start)

if __name__ == '__main__':
    main()
